/// 方块 ID
pub(crate) fn blocks() -> &'static [&'static str] {
    blocks::blocks()
}

/// 物品 ID。
///
/// 方块物品（`stone`、`oak_planks`、`white_wool` …）本身就是物品，
/// 所以这里把两份表合并，`/give` 才能给出任意方块。
pub(crate) fn items() -> &'static [&'static str] {
    static ALL: OnceLock<Vec<&'static str>> = OnceLock::new();
    ALL.get_or_init(|| {
        let mut v: Vec<&'static str> = Vec::new();
        v.extend_from_slice(items::base_items());
        v.extend_from_slice(blocks::blocks());
        v.sort_unstable();
        v.dedup();
        v
    })
}

