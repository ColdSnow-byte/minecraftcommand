//! Minecraft 26.3 注册表：引擎要用到的所有「名字表」都集中在这里。
//!
//! 引擎主体（[`crate::api::minecraft`]）只负责解析与校验，至于世界上到底有
//! 哪些方块、物品、音效、生物…… 一律从这个模块取，两边互不干扰。
//!
//! 拆成子模块的理由是数据量太大，而且生成规则各不相同：
//! - [`items`]：物品（含 `颜色 × 后缀`、`材质 × 工具`、刷怪蛋等展开）
//! - [`blocks`]：方块（含染色方块、木种构件展开）
//! - [`components`]：物品组件 `[...]` 与旧式 NBT `{...}` 的键名表
//! - [`names`]：中文词典，把英文 ID 翻成中文用于执行反馈
//!
//! 本文件放「没有展开规则、手写即可」的表，以及给引擎用的统一入口。

