static BLOCKS: OnceLock<Vec<&'static str>> = OnceLock::new();

/// 生成后的完整方块表（进程内只算一次）
pub(crate) fn blocks() -> &'static [&'static str] {
    BLOCKS.get_or_init(|| {
        let mut v: Vec<&'static str> = BASE_BLOCKS.to_vec();

        for color in DYE_COLORS {
            for suffix in COLORED_SUFFIXES {
                v.push(intern(format!("{color}_{suffix}")));
            }
        }
        for wood in WOODS {
            for suffix in WOOD_SUFFIXES {
                v.push(intern(format!("{wood}_{suffix}")));
            }
        }

        v.sort_unstable();
        v.dedup();
        v
    })
}

fn intern(s: String) -> &'static str {
    Box::leak(s.into_boxed_str())
}
